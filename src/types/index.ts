export interface OrderItem {
  productId: string;
  name: string;
  price: number;
  qty: number;
}

export type PaymentMethod =
  | 'counter'
  | 'online'
  | 'cash'
  | 'online_upi'
  | 'online_card'
  | 'online_netbanking'
  | 'online_wallet'
  | 'online_paylater';

export type OrderStatus =
  | 'payment_pending'
  | 'payment_failed'
  | 'placed'
  | 'order_confirmed'
  | 'order_failed_to_confirm'
  | 'preparing_order'
  | 'packed'
  | 'dispatched'
  | 'delivered'
  | 'failed_delivery';

// Mirrors the Order shape written by the HLBRStore storefront app (hlbr_store_orders).
// Keep in sync with that repo's src/types/index.ts.
export interface Order {
  orderId: string;
  /** Store that fulfils this order, e.g. "UPLKO0001". Riders only see and deliver their own store's orders. */
  storeId: string;
  /** Short human-readable number (storeId + DDMMYY + daily sequence), generated by the storefront. */
  orderNumber: string;
  mobileNumber: string;
  customerName: string;
  items: OrderItem[];
  floor: string;
  unitNo: string;
  itemsTotal: number;
  deliveryFee: number;
  orderTotal: number;
  status: OrderStatus;
  statusComment?: string;
  /**
   * Payment details, grouped in one object. Written by SperdyWalkin (online payment) and HLBRStoreCoord (counter
   * payments). Absent on orders that never went through payment tracking: a missing object does NOT mean unpaid.
   */
  payments?: {
    paymentStatus?: 'pending' | 'paid' | 'failed';
    /**
     * "counter": the customer will pay at the counter (unpaid). "online": paying online, not settled yet. Once paid:
     * "cash" or "online_upi" / "online_card" / ...
     */
    paymentMethod?: PaymentMethod;
    paidAt?: string;
    /** employeeId of the coordinator who recorded a counter payment as paid. */
    paymentRecordedBy?: string;
  };
  /** "walkin" for orders placed on the walk-in panel (SperdyWalkin). Absent on online orders. */
  orderType?: 'walkin';
  /** "pickup" when the customer collects at the store (always the case for walk-in orders). Absent on older orders: those are deliveries. */
  fulfillmentType?: 'delivery' | 'pickup';
  /** The online customer's users-table key. Set by the storefront only: walk-in orders have no user. */
  userId?: string;
  /** True once this order's items have been taken out of the store's stock (written by HLBRStoreCoord). */
  stockDeducted?: boolean;
  createdAt: string;

  // --- Fields this app depends on / writes ---
  /** Delivery executive this dispatched order is assigned to. Set by HLBRStoreCoord when dispatching. */
  assignedTo?: string;
  /** Secret the customer reads out to the rider. Written by the storefront; never sent to the browser here. */
  deliveryPasscode?: string;
  /** Passcode guesses used so far (owned by this app). */
  passcodeAttempts?: number;
  /** Set by this app when a rider completes the delivery. */
  deliveredAt?: string;
  deliveredBy?: string;
}

/** An order as sent to riders' browsers: the passcode and attempt counter are stripped. */
export type RiderOrder = Omit<Order, 'deliveryPasscode' | 'passcodeAttempts'>;

export interface Rider {
  employeeId: string;
  /** The one store this rider delivers for; scopes every order they can see or deliver. */
  storeId: string;
  passwordHash: string;
  name: string;
  createdAt: string;
}

export interface SessionPayload {
  employeeId: string;
  [key: string]: unknown;
}
