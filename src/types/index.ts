export interface OrderItem {
  productId: string;
  name: string;
  price: number;
  qty: number;
}

export type OrderStatus =
  | 'payment_pending'
  | 'payment_failed'
  | 'placed'
  | 'order_confirmed'
  | 'order_failed_to_confirm'
  | 'packed'
  | 'dispatched'
  | 'delivered'
  | 'failed_delivery';

// Mirrors the Order shape written by the HLBRStore storefront app (hlbr_store_orders).
// Keep in sync with that repo's src/types/index.ts.
export interface Order {
  orderId: string;
  /** Store that fulfils this order, e.g. "UPLKO0001". Riders only see and deliver their own store's orders. */
  storeId: string;
  /** Short human-readable number (storeId + DDMMYY + daily sequence), generated by the storefront. */
  orderNumber: string;
  mobileNumber: string;
  customerName: string;
  items: OrderItem[];
  floor: string;
  unitNo: string;
  itemsTotal: number;
  deliveryFee: number;
  orderTotal: number;
  status: OrderStatus;
  statusComment?: string;
  /**
   * Set by SperdyWalkin (online payment). Absent on orders that never went through online payment: a missing
   * value does NOT mean unpaid.
   */
  paymentStatus?: 'pending' | 'paid' | 'failed';
  paidAt?: string;
  createdAt: string;

  // --- Fields this app depends on / writes ---
  /** Delivery executive this dispatched order is assigned to. Set by HLBRStoreCoord when dispatching. */
  assignedTo?: string;
  /** Secret the customer reads out to the rider. Written by the storefront; never sent to the browser here. */
  deliveryPasscode?: string;
  /** Passcode guesses used so far (owned by this app). */
  passcodeAttempts?: number;
  /** Set by this app when a rider completes the delivery. */
  deliveredAt?: string;
  deliveredBy?: string;
}

/** An order as sent to riders' browsers: the passcode and attempt counter are stripped. */
export type RiderOrder = Omit<Order, 'deliveryPasscode' | 'passcodeAttempts'>;

export interface Rider {
  employeeId: string;
  /** The one store this rider delivers for; scopes every order they can see or deliver. */
  storeId: string;
  passwordHash: string;
  name: string;
  createdAt: string;
}

export interface SessionPayload {
  employeeId: string;
  [key: string]: unknown;
}
